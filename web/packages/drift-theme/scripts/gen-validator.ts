/**
 * Compiles theme.schema.json into a standalone validator so the browser never calls `new Function`
 * (Ajv's runtime compiler), which a CSP without 'unsafe-eval' blocks.
 *
 *   pnpm --filter @cutwire/drift-theme gen:validator
 *
 * The output is committed; the sync script runs this after copying a new schema.
 */
import Ajv2020 from "ajv/dist/2020.js"
import standaloneCode from "ajv/dist/standalone/index.js"
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const schema = JSON.parse(readFileSync(join(pkg, "src/generated/theme.schema.json"), "utf8"))
const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } })
// Ajv's ESM output still pulls its runtime helpers in with require(), which a browser bundle cannot resolve.
const requires: string[] = []
const code = standaloneCode(ajv, ajv.compile(schema)).replace(/const (\w+) = require\("([^"]+)"\)\.default;/g, (_, name: string, mod: string) => {
  requires.push(`import ${name}Module from "${mod}.js"`, `const ${name} = ${name}Module.default ?? ${name}Module`)
  return ""
})
if (code.includes("require(")) throw new Error("unhandled require() in the generated validator")
writeFileSync(
  join(pkg, "src/generated/theme.validator.js"),
  `// @generated by scripts/gen-validator.ts; do not edit\n/* oxlint-disable */\n${requires.join("\n")}\n${code.replace('"use strict";', "")}`,
)
